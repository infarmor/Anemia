def main() -> None:
    path = pathlib.Path(__file__).resolve().parent.parent / "core/src/test/resources/switch/due.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    for row in ROWS:
        cells = list(row) + [""] * (COLS - len(row))
        assert len(cells) == COLS, row
        lines.append("\t".join(cells[:len(row)]) if len(row) < COLS else "\t".join(cells))
    # Строка без ярлыка: пустое первое поле, все колонки на месте.
    lines[-1] = "\t".join(["", "1", "1", "0", "2", "2", "120", ""])
    path.write_text("\n".join(lines) + "\n")
    print(f"→ {path.relative_to(path.parents[3])}: {len(lines)} кейсов")


if __name__ == "__main__":
    main()
