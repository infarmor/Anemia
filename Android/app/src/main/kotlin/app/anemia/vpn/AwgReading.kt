package app.anemia.vpn

import app.anemia.core.TrafficCounters

/**
 * Какое показание AmneziaWG имеет право стать базовой линией проверки здоровья.
 * Только что прочитанное, никогда не сохранённое: `Engine.status` отвечает всеми
 * восемью ключами всегда, поэтому «нулей в ответе» здесь не бывает.
 *
 * Отдельный предикат, а не строчки внутри `checkHealth`, по той же причине, по
 * которой из расширения уже вынули `TunnelHealth` и `HealthSchedule`: правило
 * видно только на устройстве, а устройство не проверит, что правило не сдвинули.
 *
 * Четыре отказа, каждый — случай, который уже случался:
 *  - движок отчитался не собой (`engine` пустой или «xray»): `AnemiaStatus`
 *    отвечает всегда и всеми восемью ключами, даже когда движка нет, а счётчики
 *    в таком ответе — нули;
 *  - ключей `up`/`down` нет вовсе — ответ другой схемы, и `Engine.status`
 *    подставляет на их место нули (см. `Engine.Status`);
 *  - оба счётчика нулевые. `awgTraffic` превращает сорвавшийся `IpcGet` в
 *    `(0, 0, 0)`, не теряя ни одного ключа и не меняя `engine` на чужое, так что
 *    «ключи на месте» от этого не защищает. Нуль, записанный базовой линией,
 *    стоит дорого: следующая дельта равна уже накопленным байтам, `received > 0`
 *    в `TunnelHealth.counters` идёт первым условием, полоса отказов обнуляется,
 *    и при AmneziaWG переключение не наступает никогда.
 *  - накопленное отмоталось назад: за время жизни движка счётчики только растут,
 *    поэтому назад они идут только вместе со сброшенным раном — такое показание
 *    не связка с предыдущим, и вычитать из него нельзя.
 *
 * Ровно одно показание не обязано быть подвижным: идентичное предыдущему. Это
 * «телефон ничего не отправлял» (погасший экран), и `TunnelHealth.counters`
 * отвечает на него молчанием, а не отказом.
 */
object AwgReading {
    /** null — показание принимается; иначе причина, почему его нельзя считать. */
    fun refusal(
        engine: String,
        missingKeys: List<String>,
        current: TrafficCounters,
        previous: TrafficCounters?,
    ): String? {
        if (engine != "awg") return "движок отчитался не собой: «$engine»"
        if (missingKeys.any { it == "up" || it == "down" }) {
            return "в ответе нет счётчиков ${missingKeys.joinToString()}"
        }
        if (current.up == 0L && current.down == 0L) return "оба счётчика нулевые"
        if (previous != null && (current.up < previous.up || current.down < previous.down)) {
            return "счётчики отмотались ${previous.up}/${previous.down} → " +
                "${current.up}/${current.down}"
        }
        return null
    }
}
